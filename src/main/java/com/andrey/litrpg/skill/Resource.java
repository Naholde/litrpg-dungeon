package com.andrey.litrpg.skill;

/**
 * Свой ресурс класса. Маны нет: у большинства классов навыки работают только на перезарядке;
 * ресурс есть лишь там, где он и есть идея класса.
 * <p>Как ресурс копится — {@link Gain}; {@code amount} — сколько за событие (или в секунду для {@link Gain#REGEN}),
 * {@code decay} — сколько тает в секунду, если 5 секунд ничего не приходило (0 — не тает).
 */
public enum Resource {
    NONE("", 0, 0, Gain.NONE, 0, 0),
    /** Ярость берсерка: копится от ударов (своих и по себе), тает вне боя. */
    RAGE("Ярость", 100, 0xFFD8343A, Gain.FIGHT, 6, 3),
    /** Кровь кровавого рыцаря: копится от полученного урона, тратится на лечение и «Неумирающего». */
    BLOOD("Кровь", 100, 0xFF8B1A1A, Gain.TAKEN, 7, 1),
    /** Стекло зерцала: копится только пока держится «Стекло» — его и даёт сам навык. */
    GLASS("Стекло", 100, 0xFFB0E8FF, Gain.MANUAL, 0, 0),
    /** Разгон стрижа: даётся его навыками, быстро тает, если стоять. */
    MOMENTUM("Разгон", 100, 0xFF7FF0D0, Gain.CAST, 12, 8),
    /** Ци монаха: по единице за удар навыком, не тает. */
    CHI("Ци", 100, 0xFFFFD27A, Gain.CAST, 10, 0),
    /** Тень: копится в темноте и за убийства. */
    SHADE("Тень", 100, 0xFF9B5CFF, Gain.KILL, 25, 2),
    /** Дыхание снайпера: копится, пока стоишь на месте. */
    BREATH("Дыхание", 100, 0xFFE8F0FF, Gain.REGEN, 14, 0),
    /** Жар пироманта: копится от его же огня; на максимуме пиромант горит сам. */
    HEAT("Жар", 100, 0xFFFF7A2E, Gain.CAST, 14, 4),
    /** Заряд механика: копится от выстрелов и станков. */
    CHARGE("Заряд", 100, 0xFFC9D6E8, Gain.DEALT, 5, 0),
    /** Души: за убитых (призыватель, жнец). */
    SOULS("Души", 100, 0xFFBFE8FF, Gain.KILL, 20, 0),
    /** Песок хронолога: сам сыпется. */
    SAND("Песок", 100, 0xFFFFE27A, Gain.REGEN, 8, 0),
    /** Пакт чернокнижника: даётся только за своё здоровье. */
    PACT("Пакт", 100, 0xFFB0001A, Gain.MANUAL, 0, 0),
    /** Сумерки теневого жреца: копятся от нанесённого урона. */
    TWILIGHT("Сумерки", 100, 0xFF6B4AA8, Gain.DEALT, 6, 2),
    /** Морок иллюзиониста: копится от его навыков. */
    MIRAGE("Морок", 100, 0xFFD6A6FF, Gain.CAST, 15, 3),
    /** Сферы астроманта: их всего три, каждая — одна единица; даются навыками сфер. */
    SPHERES("Сферы", 3, 0xFF7FD8FF, Gain.MANUAL, 0, 0);

    /** Откуда ресурс берётся. */
    public enum Gain {
        /** Ниоткуда (ресурса нет). */
        NONE,
        /** За нанесённый удар. */
        DEALT,
        /** За полученный удар. */
        TAKEN,
        /** И за свои удары, и за полученные. */
        FIGHT,
        /** За убитого врага. */
        KILL,
        /** За применение навыка класса. */
        CAST,
        /** Сам копится каждую секунду (у снайпера — только пока стоишь на месте). */
        REGEN,
        /** Только из самих навыков класса ({@code ctx.gain}). */
        MANUAL
    }

    public final String title;
    public final double max;
    public final int color;
    public final Gain gain;
    public final double amount;
    public final double decay;

    Resource(String title, double max, int color, Gain gain, double amount, double decay) {
        this.title = title;
        this.max = max;
        this.color = color;
        this.gain = gain;
        this.amount = amount;
        this.decay = decay;
    }
}
