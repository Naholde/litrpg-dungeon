package com.andrey.litrpg.skill;

/** Как навык выбирает цель. */
public enum Targeting {
    /** На себя или вокруг себя. */
    SELF,
    /** Враг под прицелом; промах — ближайший к линии взгляда в конусе 14°. Нет врага — навык не срабатывает. */
    ENEMY,
    /** Союзник: выбранный Ctrl+1…5 → под прицелом → сам. */
    ALLY,
    /** Точка на земле под прицелом (в пределах дальности). */
    GROUND,
    /** В направлении взгляда (конус, полоса, снаряд) — цель не нужна. */
    DIRECTION
}
