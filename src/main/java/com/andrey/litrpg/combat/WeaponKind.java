package com.andrey.litrpg.combat;

/** Чем нанесён урон — от этого зависит, какая характеристика его усиливает. */
public enum WeaponKind {
    /** Меч, топор, кулак — Сила. */
    MELEE,
    /** Лук и стрелы — Ловкость. */
    RANGED,
    /** Посох — Интеллект (сила навыков). */
    MAGIC,
    /** Навык класса — Интеллект (сила навыков). */
    SKILL,
    /** Без усиления характеристиками (ловушки, окружение); множитель роли и крит — есть. */
    PLAIN,
    /** Уже посчитано заранее (урон со временем, отложенные удары): ни усиления, ни роли, ни крита. */
    FIXED
}
