package com.andrey.litrpg.status;

/**
 * Виды меток со сроком. Один обработчик урона ({@code DamageService}) читает их все — классы не пишут свои.
 * {@code magnitude} для каждого вида:
 */
public enum StatusType {
    /** Оглушение: не двигается, не бьёт, не применяет навыки. */
    STUN("Оглушение", false),
    /** Обездвиживание: не двигается, но бьёт и колдует. */
    ROOT("Обездвиживание", false),
    /** Замедление: magnitude — доля снижения скорости (0,4 = −40%). */
    SLOW("Замедление", false),
    /** Ускорение бега: magnitude — доля прибавки. */
    SPEED("Ускорение", true),
    /** Множитель получаемого урона (1,2 — уязвимость, 0,7 — защита). Несколько — перемножаются. */
    DAMAGE_TAKEN("Получаемый урон", false),
    /** Множитель наносимого урона. */
    DAMAGE_DEALT("Наносимый урон", true),
    /** Множитель получаемого лечения (0 — «нельзя лечиться»). */
    HEAL_TAKEN("Получаемое лечение", true),
    /** Щит-поглощение: magnitude — сколько урона ещё впитает. */
    SHIELD("Щит", true),
    /** Защитник: доля урона по носителю уходит источнику метки (танк «Под прикрытие»). */
    GUARD("Под защитой", true),
    /** Отражение: доля урона в ближнем бою возвращается бьющему. */
    REFLECT("Отражение", true),
    /** Вампиризм: доля нанесённого урона лечит носителя. */
    LEECH("Вампиризм", true),
    /** Урон со временем: magnitude — урон за срабатывание. */
    DOT("Урон со временем", false),
    /** Лечение со временем: magnitude — лечение за срабатывание. */
    HOT("Лечение со временем", true),
    /** Немота: нельзя применять навыки. */
    SILENCE("Немота", false),
    /** Смертельный удар оставляет 1 здоровья. */
    WARD("Несокрушимость", true),
    /** Горение: слои пироманта. Сила слоя — сумма; сам урон наносит {@code DOT}. */
    BURN("Горение", false),
    /** Обморожение: слои криоманта и бастиона (сумма — сколько слоёв). */
    CHILL("Обморожение", false),
    /** Скован льдом: не двигается; раскол по скованному бьёт втрое. */
    FROZEN("Скован", false),
    /** Статика громовержца: слои; на пятом — разряд. */
    STATIC("Статика", false),
    /** Зараза чумного владыки: слои, переходят на соседей. */
    PLAGUE("Зараза", false),
    /** Метка: цель отмечена (снайпер, жнец) — свои навыки по метке бьют иначе. */
    MARK("Метка", false),
    /** Удары по носителю проходят мимо с вероятностью magnitude (зеркала, тьма, пируэт). */
    BLUR("Удары мимо", true),
    /** Непоколебимость: оглушение, обездвиживание, замедление и обморожение не действуют. */
    STEADFAST("Непоколебимость", true),
    /** Ускорение навыков: magnitude — доля срезанной перезарядки (суммируется с Интеллектом). */
    HASTE("Короче перезарядки", true),
    /** Клеймо: доля урона по носителю лечит того, кто клеймо поставил. */
    SIPHON("Клеймо", false),
    /** Искупление: урон, нанесённый источником метки, лечит носителя на долю. */
    ATONEMENT("Искупление", true),
    /** Копит полученный урон: magnitude растёт на каждый удар (стекло зерцала, приговор, перемотка). */
    RECORD("Счёт урона", false);

    public final String title;
    /** Полезна ли носителю (для цвета значка). */
    public final boolean good;

    StatusType(String title, boolean good) {
        this.title = title;
        this.good = good;
    }

    /** Мешает ли двигаться. */
    public boolean immobilizes() {
        return this == STUN || this == ROOT || this == FROZEN;
    }

    /** Метки, от которых защищает «Непоколебимость». */
    public boolean controlling() {
        return this == STUN || this == ROOT || this == SLOW || this == FROZEN || this == CHILL;
    }

    /** Метка-счётчик: сила каждой — один слой, важна их сумма. */
    public boolean stacking() {
        return this == BURN || this == CHILL || this == STATIC || this == PLAGUE;
    }
}
