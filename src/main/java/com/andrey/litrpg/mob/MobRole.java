package com.andrey.litrpg.mob;

/** Роль монстра в отряде — от неё поведение. Отряды смешивают роли, как группы игроков. */
public enum MobRole {
    /** Громила: идёт напролом, бьёт сильно; элитный — удар по площади с разметкой. */
    BRUTE,
    /** Быстрый боец ближнего боя: догоняет лекарей и стрелков. */
    SKIRMISHER,
    /** Лучник: держит дистанцию, стреляет. */
    ARCHER,
    /** Заклинатель: снаряды с короткой подготовкой. */
    CASTER,
    /** Лекарь: лечит раненых союзников — его бьют первым. */
    HEALER,
    /** Страж: щит спереди режет урон — заходите со спины. */
    GUARD,
    /** Рой: слабые и быстрые, по нескольку. */
    SWARM
}
