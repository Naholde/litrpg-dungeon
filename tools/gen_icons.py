def icon(sid):
    cls = sid.split(".")[0]
    base = hexrgb(PALETTE.get(cls, "#9AB0D0"))
    light, dark = shade(base, 1.35), shade(base, 0.55)
    glow = tuple(min(255, int(v * 0.4 + 255 * 0.6)) for v in base)
    c = Canvas(16, 16)
    # фон: тёмная плитка с отливом цвета класса к центру
    for y in range(16):
        for x in range(16):
            d = ((x - 7.5) ** 2 + (y - 7.5) ** 2) ** 0.5
            k = max(0.0, 1 - d / 10)
            c.set(x, y, (int(10 + base[0] * 0.18 * k), int(14 + base[1] * 0.18 * k), int(24 + base[2] * 0.2 * k), 255))
    for i in range(16):
        for (x, y) in ((i, 0), (i, 15), (0, i), (15, i)):
            c.set(x, y, dark)
    for (x, y) in ((0, 0), (15, 0), (0, 15), (15, 15)):
        c.set(x, y, (6, 8, 14, 255))
    rows = MOTIFS[motif_for(sid)]
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            col = {"#": base, "+": light, "-": dark, "*": glow}.get(ch)
            if col:
                c.set(x + 2, y + 2, col)
    return c


